export function t(lang: SupportedLang, key: string): string {
  const dict = DICTIONARY[lang] || DICTIONARY['en'];
  return dict[key] || DICTIONARY['en'][key] || key;
}

export function formatDate(isoString: string, lang: SupportedLang): string {
  try {
    const date = new Date(isoString);
    const localeMap: Record<SupportedLang, string> = {
      en: 'en-IN',
      hi: 'hi-IN',
      kn: 'kn-IN',
      te: 'te-IN',
    };
    return new Intl.DateTimeFormat(localeMap[lang] || 'en-IN', {
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    }).format(date);
  } catch {
    return isoString;
  }
}
